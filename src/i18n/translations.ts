export function applyDocumentLanguagePreferences(lang: SupportedLang) {
  if (typeof document === 'undefined') return;
  const meta = LANG_META[lang] || LANG_META.EN;
  document.documentElement.lang = meta.code.toLowerCase();
  document.documentElement.dir = meta.dir;
}

export function normalizePrimaryLang(lang: SupportedLang): SupportedLang {
  return lang;
}

